"""Step 3, SonarQube, with the real server and scanner images (`pytest -m docker`).

Needs the running server (`docker compose -f docker/docker-compose.yml up -d`),
the scanner images (`--profile tools build sonar-scanner sonar-dotnet`) and
SONARQUBE_ADMIN_PASSWORD (environment or docker/.env). The server is reached
at http://127.0.0.1:9000 from the tests and at http://sonarqube:9000 from the
scanner containers (network code-analysis-net). The test projects must lie in
a folder Docker can mount (CODE_ANALYSIS_DOCKER_TEST_DIR).
"""

import json
import os
import shutil
import subprocess
import uuid
from pathlib import Path

import pytest
from conftest import REPOSITORY, commit_all, opengrep_config

from scheduler.acceptance import run_acceptance
from scheduler.config import Settings
from scheduler.linting.docker import DockerError, DockerRunner
from scheduler.linting.model import Status
from scheduler.static_analysis import run_static_analysis, sonarqube
from scheduler.static_analysis.sonar_api import HttpSonarApi, SonarError

pytestmark = pytest.mark.docker

API_URL = "http://127.0.0.1:9000"


def admin_password() -> str | None:
    if password := os.environ.get("SONARQUBE_ADMIN_PASSWORD"):
        return password
    env_file = REPOSITORY / "docker" / ".env"
    if env_file.is_file():
        for line in env_file.read_text().splitlines():
            if line.startswith("SONARQUBE_ADMIN_PASSWORD="):
                return line.split("=", 1)[1].strip() or None
    return None


@pytest.fixture(scope="module")
def server():
    password = admin_password()
    if not password:
        pytest.skip("SONARQUBE_ADMIN_PASSWORD is not set")
    runner = DockerRunner(network="code-analysis-net")
    try:
        runner.check_available()
        for image in (sonarqube.SCANNER_IMAGE, sonarqube.DOTNET_IMAGE):
            runner.ensure_image(image)
        if HttpSonarApi(API_URL).get("api/system/status").get("status") != "UP":
            pytest.skip("SonarQube is not up")
    except (DockerError, SonarError) as exc:
        pytest.skip(f"SonarQube or the scanner images not available: {exc}")
    return runner, password, HttpSonarApi(API_URL, login="admin", password=password)


@pytest.fixture
def workspace(tmp_path, server):
    base = Path(os.environ.get("CODE_ANALYSIS_DOCKER_TEST_DIR") or tmp_path).resolve()
    folder = base / f"itest-{uuid.uuid4().hex[:8]}"
    folder.mkdir(parents=True)
    yield folder
    shutil.rmtree(folder, ignore_errors=True)


def project(workspace: Path, files: dict[str, str]) -> Path:
    root = workspace / f"sq-{uuid.uuid4().hex[:6]}"  # own SonarQube project per test
    for relative, content in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    commit_all(root)
    return root


def analyse(root: Path, workspace: Path, server):
    runner, password, api = server
    settings = Settings(projects_dir=None, host_home=None, ollama_base_url="x", output_dir=workspace / "results",
                        config_dir=opengrep_config(workspace / "config"), sonarqube_url=API_URL,
                        sonarqube_scanner_url="http://sonarqube:9000", sonarqube_admin_password=password)
    acceptance = run_acceptance(root)
    assert acceptance.accepted, acceptance.message
    try:
        result = run_static_analysis(acceptance, settings, workspace / "results" / "run", runner=runner,
                                     out=lambda _: None, tools=["SonarQube"])
    finally:
        try:
            api.post("api/projects/delete", {"project": sonarqube.project_key(root)})
        except SonarError:
            pass
    (run,) = result.tool_runs
    return run


def rules(run) -> set[tuple[str, str | None]]:
    return {(finding.rule, finding.file) for finding in run.findings}


def test_python_typescript_cpp_rust(workspace, server):
    _, _, api = server
    root = project(workspace, {
        # Manifests: step 1 needs one for the primary language.
        "requirements.txt": "requests\n",
        "package.json": '{"name": "x"}\n',
        "src/crypto.py": "import hashlib\n\n\ndef digest(data):\n    return hashlib.md5(data).hexdigest()\n",
        "src/app_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\nimport hashlib\n"
                          "hashlib.md5(b'x')\n",
        "web/check.ts": "export function f(a: number): number {\n  var other = 2;\n  return a + other;\n}\n",
        "native/copy.cpp": "#include <cstring>\nvoid copy(char *d, const char *s) { strcpy(d, s); }\n",
        "rs/Cargo.toml": '[package]\nname = "rs"\nversion = "0.1.0"\nedition = "2021"\n',
        "rs/src/main.rs": "fn main() {\n    let x = 5;\n    println!(\"{}\", x);\n}\n",
        "sonar-project.properties": "sonar.exclusions=**/*.py\n",
    })
    run = analyse(root, workspace, server)
    assert run.status is Status.OK, run.notes
    weak_hash = next(finding for finding in run.findings if finding.rule == "python:S4790")
    assert weak_hash.file == "src/crypto.py" and weak_hash.cwe == ("CWE-1240",) and weak_hash.category == "security"
    assert ("typescript:S3504", "web/check.ts") in rules(run)  # "var" instead of let/const
    assert not any(finding.file == "src/app_pb2.py" for finding in run.findings)  # generated: excluded
    measured = json.loads((workspace / "results/run/step3-static-analysis/sonarqube/api/files.json").read_text())
    files = {entry["path"] for entry in measured}
    # C/C++ (sonar-cxx) and Rust are indexed and measured.
    assert {"native/copy.cpp", "rs/src/main.rs", "src/crypto.py", "web/check.ts"} <= files
    assert int(run.measures["ncloc"]) > 0
    assert {entry["language"] for entry in run.rulesets} == {"py", "ts", "cxx", "rust"}
    status = subprocess.run(["git", "-C", str(root), "status", "--porcelain"], capture_output=True, text=True)
    assert status.stdout == ""  # the project is untouched
    tokens = api.get("api/user_tokens/search", {"login": "admin"}).get("userTokens", [])
    assert not any(token["name"].startswith("code-analysis-") for token in tokens)  # revoked


def test_java_with_maven_build(workspace, server):
    root = project(workspace, {
        "pom.xml": "<project><modelVersion>4.0.0</modelVersion><groupId>x</groupId><artifactId>x</artifactId>"
                   "<version>1</version><properties><maven.compiler.release>17</maven.compiler.release>"
                   "<project.build.sourceEncoding>UTF-8</project.build.sourceEncoding></properties></project>\n",
        "src/main/java/x/A.java": "package x;\n\nimport java.io.FileInputStream;\nimport java.io.IOException;\n\n"
                                  "public class A {\n    public int read(String path) throws IOException {\n"
                                  "        FileInputStream in = new FileInputStream(path);\n"
                                  "        return in.read();\n    }\n}\n",
    })
    run = analyse(root, workspace, server)
    assert run.status is Status.OK, run.notes
    # Found only with bytecode (without it, SonarQube missed it in the evaluation).
    assert ("java:S2095", "src/main/java/x/A.java") in rules(run)
    assert run.details["java_bytecode_folders"] == ["target/classes"]


def test_csharp_with_dotnet_scanner(workspace, server):
    root = project(workspace, {
        "app.csproj": '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType>'
                      "<TargetFramework>net10.0</TargetFramework></PropertyGroup></Project>\n",
        ".gitignore": "bin/\nobj/\n",
        "Program.cs": "using System;\nusing System.Security.Cryptography;\n\nclass Program\n{\n"
                      "    static void Main()\n    {\n        var md5 = MD5.Create();\n"
                      "        Console.WriteLine(md5.ComputeHash(new byte[] { 1 }).Length);\n    }\n}\n",
        "web/site.js": "function f() {\n  var unused = 2;\n}\n",
    })
    run = analyse(root, workspace, server)
    assert run.status is Status.OK, run.notes
    assert run.details["scanner"] == "SonarScanner for .NET"
    assert ("csharpsquid:S4790", "Program.cs") in rules(run)
    assert ("javascript:S1481", "web/site.js") in rules(run)  # other languages too (scanAll)
    assert not any(finding.rule.startswith("external_roslyn:") for finding in run.findings)


def test_cpp_with_the_plugins_own_rules(workspace, server):
    root = project(workspace, {
        "conanfile.txt": "[requires]\n",
        "src/calc.cpp": "// Copyright (c) 2026 Example\n\n"
                        "int computeTotal(int a, int b, int c, int d, int e, int f, int g, int h) {\n"
                        "    return a + b + c + d + e + f + g + h;\n}\n",
    })
    run = analyse(root, workspace, server)
    assert run.status is Status.OK, run.notes
    assert run.details["cxx_profile"]["name"] == "Sonar way + sonar-cxx rules"
    assert run.details["cxx_profile"]["active_rules"] == 22
    found = rules(run)
    assert ("cxx:TooManyParameters", "src/calc.cpp") in found
    assert ("cxx:FunctionName", "src/calc.cpp") in found  # snake_case expected by default
    assert not any(rule == "cxx:FileHeader" for rule, _ in found)  # excluded
    assert {"name": "Sonar way + sonar-cxx rules", "language": "cxx"}.items() <= next(
        entry for entry in run.rulesets if entry["language"] == "cxx").items()

