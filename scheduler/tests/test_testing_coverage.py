"""Step 5.3 without Docker: coverage reports (real reports in tests/fixtures/testing/) and which source
files a suite's coverage counts."""

from pathlib import Path

import pytest
from conftest import commit_all, requires_git

from scheduler.acceptance import run_acceptance
from scheduler.testing.coverage_reports import parse_cobertura, parse_cobertura_files, parse_jacoco, ranges
from scheduler.testing.detect import detect_suites
from scheduler.testing.sources import suite_sources

FIXTURES = Path(__file__).parent / "fixtures" / "testing"
WORKSPACE = "/work/itest/run/step5-tests/workspace"  # where the reports were written (paths made neutral)


def report_in(tmp_path: Path, name: str, files: list[str]) -> tuple[Path, Path]:
    """The fixture with its paths pointing to a copy in tmp_path that has the given files."""
    workspace = tmp_path / "workspace"
    for file in files:
        (workspace / file).parent.mkdir(parents=True, exist_ok=True)
        (workspace / file).write_text("")
    text = (FIXTURES / name).read_text().replace(WORKSPACE, str(workspace))
    if name == "coverlet.xml":  # coverlet: source "/" and absolute file names without the leading slash
        text = text.replace(WORKSPACE.lstrip("/"), str(workspace).lstrip("/"))
    report = tmp_path / name
    report.write_text(text)
    return report, workspace


def summary(files):
    return {file.file: (file.lines_covered, file.lines_total, file.branches_covered, file.branches_total,
                        file.uncovered_lines) for file in files.values()}


@pytest.mark.parametrize(("name", "file", "expected"), [
    ("coverage-py.xml", "calc/__init__.py", (3, 6, 0, 2, "6-8")),  # coverage.py with branches
    ("llvm-cov.xml", "src/lib.rs", (8, 15, None, None, "11-13, 15, 17, 31, 35")),  # cargo-llvm-cov: no branches
    ("coverlet.xml", "Calc/Calculator.cs", (1, 7, 0, 2, "8-11, 13-14")),  # coverlet writes branch="True"
    ("gcovr.xml", "src/calc.c", (2, 7, 0, 2, "5-7, 9-10")),
    ("vitest-cobertura.xml", "src/calc.js", (2, 2, None, None, "")),
    ("jest-cobertura.xml", "src/calc.cjs", (1, 1, None, None, "")),
    ("c8-cobertura.xml", "src/calc.js", (3, 3, 2, 2, "")),
])
def test_cobertura_reports(tmp_path, name, file, expected):
    report, workspace = report_in(tmp_path, name, [file])
    assert summary(parse_cobertura(report, workspace)) == {file: expected}


def test_cobertura_keeps_only_files_in_the_copy(tmp_path):
    report, workspace = report_in(tmp_path, "coverage-py.xml", [])  # the file is not in the copy
    assert parse_cobertura(report, workspace) == {}


def test_cobertura_reports_are_merged_line_by_line(tmp_path):
    report, workspace = report_in(tmp_path, "coverage-py.xml", ["calc/__init__.py"])
    other = tmp_path / "other.xml"  # e.g. a second target framework that ran sign()
    other.write_text(report.read_text().replace('<line number="7" hits="0"/>', '<line number="7" hits="1"/>'))
    merged = summary(parse_cobertura_files([report, other], workspace))
    assert merged["calc/__init__.py"][:2] == (4, 6) and merged["calc/__init__.py"][4] == "6, 8"


def test_jacoco_report_is_matched_by_package_path():
    files = parse_jacoco(FIXTURES / "jacoco.xml", ["src/main/java/calc/Calc.java", "other/Calc.java"])
    assert summary(files) == {"src/main/java/calc/Calc.java": (1, 5, 0, 2, "3, 9-10, 12")}
    # Two files with the same package path: no guess.
    assert parse_jacoco(FIXTURES / "jacoco.xml", ["a/calc/Calc.java", "b/calc/Calc.java"]) == {}


def test_ranges():
    assert ranges([9, 3, 4, 5, 11, 12]) == "3-5, 9, 11-12"
    assert ranges([]) == ""


@requires_git
def test_suite_sources_leave_out_test_code_and_tooling(make_project):
    project = make_project({
        "pyproject.toml": "[project]\nname = 'x'\n",
        "calc/__init__.py": "x = 1\n" * 20,
        "calc/core.py": "y = 1\n",
        "tests/test_calc.py": "def test_x():\n    pass\n",
        "tests/helpers.py": "z = 1\n",
        "conftest.py": "",
        "setup.py": "",
        "docs/conf.py": "",
        "api/message_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\nimport x\n",
    })
    commit_all(project)
    acceptance = run_acceptance(project)
    suites, _ = detect_suites(acceptance)
    assert suite_sources(acceptance, suites, suites[0]) == ["calc/__init__.py", "calc/core.py"]


@requires_git
def test_suite_sources_of_csharp_and_javascript(make_project):
    project = make_project({
        "App/App.csproj": '<Project Sdk="Microsoft.NET.Sdk"></Project>',
        "App/Program.cs": "class Program {}\n" * 20,
        "App/obj/Generated.cs": "",  # build output
        "App.Tests/App.Tests.csproj": '<Project><ItemGroup><PackageReference Include="xunit" /></ItemGroup></Project>',
        "App.Tests/Tests.cs": "public class T { [Fact] public void A() {} }\n",
        "App.Tests/Helper.cs": "static class Helper {}\n",
        "web/package.json": '{"scripts": {"test": "jest"}}',
        "web/src/app.js": "export const a = 1;\n",
        "web/src/app.test.js": "test('a', () => {});\n",
        "web/jest.config.js": "module.exports = {};\n",
        "web/types.d.ts": "export {};\n",
    })
    commit_all(project)
    acceptance = run_acceptance(project)
    suites, _ = detect_suites(acceptance)
    by_language = {suite.language: suite for suite in suites}
    # A C# suite is a test project: its sources are the C# files outside the test projects.
    assert suite_sources(acceptance, suites, by_language["C#"]) == ["App/Program.cs"]
    assert suite_sources(acceptance, suites, by_language["JavaScript/TypeScript"]) == ["web/src/app.js"]
